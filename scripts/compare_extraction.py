def norm_cell(v) -> str:
    if v is None:
        return ''
    if isinstance(v, bool):
        return 'TRUE' if v else 'FALSE'
    if isinstance(v, float) and v.is_integer():
        return str(int(v))
    if isinstance(v, (_dt.datetime, _dt.date)):
        return v.isoformat()
    return re.sub(r'\s+', ' ', str(v)).strip()


def read_source(path: Path, schema: dict) -> dict:
    path = Path(path)
    out = {'path': str(path), 'tables': {}, 'notes': [], 'minutes': {}, 'date_finished': '', 'is_pilot': False}
    if path.is_dir():
        files = sorted(path.glob('*.csv'))
        out['sha256'] = {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in files}
        for t in list(schema['tables']) + list(EXTRA_SHEETS):
            p = path / f'{t}.csv'
            rows = list(csv.DictReader(p.open(encoding='utf-8-sig'))) if p.exists() else []
            rows = [{k: norm_cell(v) for k, v in r.items()} for r in rows]
            rows = [r for r in rows if any(r.values())]
            if t in EXTRA_SHEETS:
                out['notes'] = rows
            else:
                out['tables'][t] = rows
        p = path / README_CSV
        if p.exists():
            out['is_pilot'] = True
            for r in csv.DictReader(p.open(encoding='utf-8-sig')):
                if r.get('report_id') == '__date_finished__':
                    out['date_finished'] = norm_cell(r.get('minutes'))
                else:
                    out['minutes'][r['report_id']] = {'minutes': norm_cell(r.get('minutes')),
                                                      'questions': norm_cell(r.get('unresolved_questions'))}
        return out
    import openpyxl
    out['sha256'] = {path.name: hashlib.sha256(path.read_bytes()).hexdigest()}
    wb = openpyxl.load_workbook(path, data_only=True)
    for t in list(schema['tables']) + list(EXTRA_SHEETS):
        if t not in wb.sheetnames:
            if t in schema['tables']:
                raise SystemExit(f'{path}: sheet {t} missing')
            continue
        ws = wb[t]
        head = [norm_cell(c.value) for c in ws[1]]
        rows = []
        for row in ws.iter_rows(min_row=2, values_only=True):
            r = {h: norm_cell(v) for h, v in zip(head, row) if h}
            if any(r.values()):
                rows.append(r)
        if t in EXTRA_SHEETS:
            out['notes'] = rows
        else:
            missing = [f for f in schema['tables'][t]['fields'] if f not in head]
            if missing:
                raise SystemExit(f'{path}: sheet {t} lacks columns {missing[:5]} (not generated from this dictionary?)')
            out['tables'][t] = rows
    if 'README' in wb.sheetnames:
        rd = wb['README']
        hdr = next((c.row for c in rd['C'] if c.value == bw.PILOT_MINUTES_HEADER), None)
        if hdr:
            out['is_pilot'] = True
            r = hdr + 1
            while rd.cell(row=r, column=1).value:
                out['minutes'][norm_cell(rd.cell(row=r, column=1).value)] = {
                    'minutes': norm_cell(rd.cell(row=r, column=3).value),
                    'questions': norm_cell(rd.cell(row=r, column=4).value)}
                r += 1
        for c in rd['A']:
            if c.value == bw.PILOT_DATE_LABEL:
                out['date_finished'] = norm_cell(rd.cell(row=c.row, column=2).value)
    return out


def export(path: Path, out_dir: Path, schema: dict) -> list:
    data = read_source(path, schema)
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for t, rows in data['tables'].items():
        written.append(write_csv(out_dir / f'{t}.csv', schema['tables'][t]['fields'], rows))
    written.append(write_csv(out_dir / f'{bw.PILOT_NOTES_SHEET}.csv', bw.PILOT_NOTES_COLUMNS, data['notes']))
    mins = [{'report_id': k, 'minutes': v['minutes'], 'unresolved_questions': v['questions']}
            for k, v in data['minutes'].items()]
    if data['date_finished']:
        mins.append({'report_id': '__date_finished__', 'minutes': data['date_finished'], 'unresolved_questions': ''})
    written.append(write_csv(out_dir / README_CSV, ['report_id', 'minutes', 'unresolved_questions'], mins))
    return written


def write_csv(p: Path, cols, rows) -> str:
    with p.open('w', newline='', encoding='utf-8') as f:
        w = csv.DictWriter(f, fieldnames=list(cols), extrasaction='ignore', lineterminator='\n')
        w.writeheader()
        for r in rows:
            w.writerow({c: r.get(c, '') for c in cols})
    return str(p)


