#!/usr/bin/env python3
"""Compare two reviewers' independent extraction workbooks field by field (charting pilot and formal extraction).

Inputs are the .xlsx files generated by scripts/build_workbooks.py (after the reviewers saved them) or CSV exports
(a directory with one <table>.csv per dictionary table, plus optional pilot_notes.csv and readme_minutes.csv, as
written by the `export` command). Tables, columns, keys, list/count/coded columns and legacy modules are read from
05_extraction/data_dictionary.json through build_workbooks.extraction_fields(), so the comparison follows the same
single source as the workbooks.

Usage:
    python3 scripts/compare_extraction.py compare --a pilot_extraction_B.xlsx --b pilot_extraction_C.xlsx \\
        --label-a B --label-b C --out-dir 05_extraction/pilot_2026-10-05/compare_round1
    python3 scripts/compare_extraction.py export --in pilot_extraction_B.xlsx --out-dir <dir>   # CSV export for git
    python3 scripts/compare_extraction.py selftest                                              # synthetic pair, temp dir only

What is compared
- Rows are aligned per table by primary key (extraction_provenance: by report_id, because the pilot provenance_id
  carries the reviewer label). --align auto (default) falls back to (report_id, n-th row of that report in sheet
  order) when the two files share fewer than half of their primary keys, i.e. when the reviewers numbered their rows
  differently; the method used is reported per table. Rows found in one file only are listed, not scored.
- Every cell of a matched row that is non-empty in at least one file is scored: agree / disagree / only_<A> /
  only_<B>. Values are compared after trimming and collapsing white space; counts as integers; multi-valued ("; ")
  columns as sets. Free text is compared exactly and is reported separately (value_kind = free_text), because
  exact agreement on prose is not expected; read those disagreements, do not count them.
- Reviewer-slot columns (..._A / ..._B, e.g. screening_decision_reviewer_A/_B, extractor_a_b.extractor_A/_B,
  digitizer_A/_B) are paired across files: file A's slot --slot-a column against file B's slot --slot-b column
  (pilot: B uses slot A, C uses slot B). Values typed into the other slot are listed as slot warnings.
- Not scored (listed in the summary): columns that differ by design (provenance_id, extractor_a_b.extractor_A/_B,
  recorded_at, digitizer_A/_B) and, when both inputs are pilot workbooks, the bibliographic reports columns that
  build_workbooks.py --populate-reports pre-filled (identical by construction). Agreement is also given for coded + count cells only (coded_and_counts_only), the judgement
  fields that can agree exactly; identifiers (row keys) and free text are reported but should be read.
- Cells empty in both files are not scored; they are listed per table/field/report in empty_by_both.csv with a
  candidate reason (flagged in pilot_notes as not extractable / as unclear, or unflagged for D to classify).

Outputs (in --out-dir): agreement_summary.json, agreement_by_table.csv, agreement_by_family.csv,
agreement_by_field.csv, disagreements.csv, empty_by_both.csv, row_coverage.csv, minutes_and_questions.csv,
pilot_notes_combined.csv. Agreement figures are descriptive only; pilot data are not results.
"""
