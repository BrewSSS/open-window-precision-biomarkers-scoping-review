# Self-test on a synthetic pair (temporary directory only; no project file is written)
# ---------------------------------------------------------------------------------------------
def selftest() -> int:
    import openpyxl
    schema = load_schema()
    ok, results = True, []

    def check(label, cond):
        nonlocal ok
        results.append({'check': label, 'passed': bool(cond)})
        ok &= bool(cond)

    with tempfile.TemporaryDirectory() as td:
        td = Path(td)
        rep_csv = td / 'reports.csv'
        with rep_csv.open('w', newline='', encoding='utf-8') as f:
            w = csv.writer(f)
            w.writerow(['pilot_item_id', 'reference_id', 'title', 'authors', 'year', 'doi', 'pmid', 'url', 'pilot_purpose',
                        'fulltext_source'])
            w.writerow(['pilot_01', 'S01', 'Synthetic report one', 'Doe J', '2020', '10.0000/s01', '1', 'https://x/1', 'p1', 'PMC'])
            w.writerow(['pilot_02', 'S02', 'Synthetic report two', 'Roe R', '2021', '10.0000/s02', '2', 'https://x/2', 'p2', 'PMC'])
        files = {}
        for lab in ('B', 'C'):
            out = td / f'x_{lab}.xlsx'
            rc = bw.main(['--populate-reports', str(rep_csv), '--reviewer-label', lab, '--out', str(out)])
            check(f'generator builds and verifies pilot workbook {lab}', rc == 0)
            files[lab] = out

        def fill(path, data, minutes, notes):
            wb = openpyxl.load_workbook(path)
            for t, rows in data.items():
                ws = wb[t]
                head = [c.value for c in ws[1]]
                if t in ('reports', 'extraction_provenance'):      # pre-filled rows: match on report_id
                    for vals in rows:
                        r = next(c.row for c in ws['B' if t == 'extraction_provenance' else 'A']
                                 if c.value == vals['report_id'])
                        for k, v in vals.items():
                            ws.cell(row=r, column=head.index(k) + 1, value=v)
                    continue
                for i, vals in enumerate(rows, start=2):
                    for k, v in vals.items():
                        ws.cell(row=i, column=head.index(k) + 1, value=v)
            rd = wb['README']
            for c in rd['A']:
                if c.value in minutes:
                    rd.cell(row=c.row, column=3, value=minutes[c.value])
            ws = wb[bw.PILOT_NOTES_SHEET]
            for i, n in enumerate(notes, start=2):
                for k, v in n.items():
                    ws.cell(row=i, column=bw.PILOT_NOTES_COLUMNS.index(k) + 1, value=v)
            wb.save(path)

        r1, r2 = 'PILOT-S01', 'PILOT-S02'
        fill(files['B'], {
            'reports': [{'report_id': r1, 'screening_decision_reviewer_A': 'INCLUDE_A', 'immune_link': 'x; y',
                         'publication_status': 'peer_reviewed_version_of_record', 'reviewer_notes': 'only in B'}],
            'cohorts': [{'cohort_id': 'C-S01-1', 'study_id': 'S-S01-1', 'n_recruited': 12, 'age_range': '20-30'}],
            'report_cohort_links': [{'link_id': 'L-S01-1', 'report_id': r1, 'study_id': 'S-S01-1',
                                     'cohort_id': 'C-S01-1'}],
            'sample_sets': [{'sample_set_id': 'SS-S01-01', 'report_id': r1, 'time_bin': 'pre_exercise_baseline'},
                            {'sample_set_id': 'SS-S01-02', 'report_id': r1, 'time_bin': '0_to_lt30min'}],
            'measurements': [{'measurement_id': 'M-S01-001', 'report_id': r1, 'marker_family': 'mucosal_sIgA'},
                             {'measurement_id': 'M-S01-002', 'report_id': r1, 'marker_family': 'proteome'}],
            'extraction_provenance': [{'report_id': r1, 'extractor_a_b.extractor_A': 'B'}],
        }, {r1: 30, r2: 12.5}, [])
        fill(files['C'], {
            'reports': [{'report_id': r1, 'screening_decision_reviewer_B': 'INCLUDE_A', 'immune_link': 'y; x',
                         'publication_status': 'peer_reviewed_version_of_record',
                         'screening_decision_reviewer_A': 'WRONG_SLOT'}],
            'cohorts': [{'cohort_id': 'C-S01-1', 'study_id': 'S-S01-1', 'n_recruited': '12', 'age_range': '21-30'}],
            'report_cohort_links': [{'link_id': 'L-S01-1', 'report_id': r1, 'study_id': 'S-S01-1',
                                     'cohort_id': 'C-S01-1'}],
            'sample_sets': [{'sample_set_id': 'SS-S01-01', 'report_id': r1, 'time_bin': 'pre_exercise_baseline'}],
            'measurements': [{'measurement_id': 'X1', 'report_id': r1, 'marker_family': 'mucosal_sIgA'},
                             {'measurement_id': 'X2', 'report_id': r1, 'marker_family': 'metabolome_or_lipidome'}],
            'extraction_provenance': [{'report_id': r1, 'extractor_a_b.extractor_B': 'C'}],
        }, {r1: 45}, [{'report_id': r1, 'table': 'cohorts', 'field': 'sport', 'issue_type': 'not_extractable_from_text',
                       'question': 'sport not stated'},
                      {'report_id': r1, 'table': 'cohorts', 'field': 'training_status', 'issue_type': 'definition_ambiguous',
                       'question': 'unclear'}])

        def run(a, b, out):
            ns = argparse.Namespace(a=a, b=b, label_a='B', label_b='C', slot_a='A', slot_b='B', align='auto',
                                    no_slot_pairing=False, out_dir=out)
            run_compare(ns)
            return json.loads((out / 'agreement_summary.json').read_text())

        s = run(files['B'], files['C'], td / 'cmp')
        T = s['tables']
        dis = list(csv.DictReader((td / 'cmp' / 'disagreements.csv').open(encoding='utf-8')))
        emp = list(csv.DictReader((td / 'cmp' / 'empty_by_both.csv').open(encoding='utf-8')))
        mins = list(csv.DictReader((td / 'cmp' / 'minutes_and_questions.csv').open(encoding='utf-8')))
        rep = T['reports']
        check('reports aligned by key on 2 pre-filled rows', rep['align'] == 'key:report_id' and rep['rows_matched'] == 2)
        check('generator pre-filled bibliographic cells are not scored; 3 judgement cells agree',
              rep['agree'] == 3 and 'reports.title' in s['not_scored_columns'])
        check('slot pairing: B slot A vs C slot B counted as agreement',
              not any(d['field'].startswith('screening_decision_reviewer') for d in dis))
        check('wrong-slot entry reported as slot warning',
              any(w['column'] == 'screening_decision_reviewer_A' and w['reviewer'] == 'C' for w in s['slot_warnings']))
        check('multi-valued field compared as a set', not any(d['field'] == 'immune_link' for d in dis))
        check('one-sided cell listed as only_B', any(d['field'] == 'reviewer_notes' and d['category'] == 'only_B' for d in dis))
        coh = T['cohorts']
        check('cohorts: count 12 vs "12" agrees; age_range disagrees',
              coh['agree'] == 2 and coh['disagree'] == 1 and any(d['field'] == 'age_range' and d['value_B'] == '20-30'
                                                                  and d['value_C'] == '21-30' for d in dis))
        check('sample_sets: one row only in B', T['sample_sets']['rows_only_B'] == 1 and T['sample_sets']['rows_matched'] == 1)
        check('measurements: different IDs -> ordinal alignment, 1 agree + 1 disagree on marker_family',
              T['measurements']['align'].startswith('ordinal') and T['measurements']['agree'] >= 1
              and any(d['field'] == 'marker_family' and d['category'] == 'disagree' for d in dis))
        check('provenance aligned by report_id; reviewer-identity columns not scored',
              T['extraction_provenance']['align'] == 'key:report_id' and T['extraction_provenance']['rows_matched'] == 2
              and not any(d['table'] == 'extraction_provenance' for d in dis))
        check('coded+count agreement excludes identifiers and free text',
              T['measurements']['coded_and_counts_only']['agree'] == 1
              and T['measurements']['coded_and_counts_only']['disagree'] == 1)
        check('empty-by-both flagged as not extractable when a reviewer said so',
              any(e['field'] == 'sport' and e['candidate_reason'].startswith('not_extractable') for e in emp))
        check('empty-by-both flagged as unclear for definition_ambiguous',
              any(e['field'] == 'training_status' and e['candidate_reason'].startswith('manual_or_dictionary_unclear')
                  for e in emp))
        check('unflagged empty-by-both left for D', any(e['candidate_reason'].startswith('unflagged') for e in emp))
        check('minutes read per report from README',
              any(m['report_id'] == r1 and m['minutes_B'] == '30' and m['minutes_C'] == '45' for m in mins)
              and any(m['report_id'] == r2 and m['minutes_B'] == '12.5' for m in mins))
        # CSV export path gives identical results
        export(files['B'], td / 'csv_B', schema)
        export(files['C'], td / 'csv_C', schema)
        s2 = run(td / 'csv_B', td / 'csv_C', td / 'cmp_csv')
        check('CSV exports give the same agreement as the workbooks',
              s2['overall'] == s['overall'] and s2['disagreement_categories'] == s['disagreement_categories'])
    passed = sum(r['passed'] for r in results)
    print(json.dumps({'selftest': 'PASS' if ok else 'FAIL', 'passed': passed, 'total': len(results),
                      'failed': [r['check'] for r in results if not r['passed']]}, ensure_ascii=False))
    return 0 if ok else 1


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest='cmd', required=True)
    c = sub.add_parser('compare', help='compare two extraction workbooks / CSV-export directories')
    c.add_argument('--a', type=Path, required=True, help='first reviewer (.xlsx or CSV directory)')
    c.add_argument('--b', type=Path, required=True, help='second reviewer (.xlsx or CSV directory)')
    c.add_argument('--label-a', default='B', help='label of --a (default B: pilot reviewer B)')
    c.add_argument('--label-b', default='C', help='label of --b (default C: pilot reviewer C)')
    c.add_argument('--slot-a', default='A', choices=['A', 'B'], help='slot columns used by --a (default A)')
    c.add_argument('--slot-b', default='B', choices=['A', 'B'], help='slot columns used by --b (default B)')
    c.add_argument('--no-slot-pairing', action='store_true', help='compare *_A with *_A and *_B with *_B')
    c.add_argument('--align', choices=['auto', 'key', 'ordinal'], default='auto')
    c.add_argument('--out-dir', type=Path, required=True)
    e = sub.add_parser('export', help='write one CSV per table (+ pilot_notes, README minutes) for git')
    e.add_argument('--in', dest='inp', type=Path, required=True)
    e.add_argument('--out-dir', type=Path, required=True)
    sub.add_parser('selftest', help='synthetic pair in a temporary directory')
    args = ap.parse_args(argv)
    if args.cmd == 'compare' and args.label_a == args.label_b:
        ap.error('--label-a and --label-b must differ')
    if args.cmd == 'compare':
        return run_compare(args)
    if args.cmd == 'export':
        print(json.dumps({'written': export(args.inp, args.out_dir, load_schema())}, ensure_ascii=False))
        return 0
    return selftest()


if __name__ == '__main__':
    sys.exit(main())
