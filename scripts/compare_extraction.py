def norm_value(v: str, meta: dict) -> str:
    if v == '':
        return ''
    if meta['is_list']:
        return '; '.join(sorted({x.strip() for x in v.split(';') if x.strip()}))
    if meta['kind'] == 'count':
        try:
            f = float(v)
            return str(int(f)) if f.is_integer() else str(f)
        except ValueError:
            return v
    return v


def align(rows_a, rows_b, key: str, mode: str):
    """Return (pairs, only_a, only_b, method, duplicates)."""
    def keyed(rows, k):
        d, dup = {}, []
        for r in rows:
            kv = r.get(k, '')
            if kv in d:
                dup.append(kv)
                continue
            d[kv] = r
        return d, dup

    def ordinal(rows):
        seen, d = Counter(), {}
        for r in rows:
            rid = r.get('report_id', '')
            seen[rid] += 1
            d[f'{rid}#{seen[rid]}'] = r
        return d, []

    method = 'key:' + key
    da, dupa = keyed(rows_a, key)
    db, dupb = keyed(rows_b, key)
    if mode == 'ordinal' or (mode == 'auto' and key != 'report_id' and rows_a and rows_b
                             and 'report_id' in rows_a[0]
                             and len(set(da) & set(db)) < 0.5 * min(len(da), len(db))):
        da, dupa = ordinal(rows_a)
        db, dupb = ordinal(rows_b)
        method = 'ordinal:report_id#n'
    keys = list(dict.fromkeys(list(da) + list(db)))
    pairs = [(k, da[k], db[k]) for k in keys if k in da and k in db]
    only_a = [(k, da[k]) for k in keys if k in da and k not in db]
    only_b = [(k, db[k]) for k in keys if k in db and k not in da]
    return pairs, only_a, only_b, method, dupa + dupb


def compare(a: dict, b: dict, schema: dict, la: str, lb: str, slot_a: str, slot_b: str, mode: str = 'auto',
            pair_slots: bool = True) -> dict:
    by_field = defaultdict(Counter)
    meta_of = {}
    disagreements, empty, coverage, slot_warn, tables_out = [], [], [], [], {}
    notes = [dict(n, reviewer=la) for n in a['notes']] + [dict(n, reviewer=lb) for n in b['notes']]
    flagged = defaultdict(set)
    for n in notes:
        for fld in [x.strip() for x in n.get('field', '').split(';') if x.strip()]:
            flagged[(n.get('table', ''), fld, n.get('report_id', ''))].add(n.get('issue_type', '') or 'unspecified')
    # cohorts / study_families carry no report_id: resolve through either reviewer's report_cohort_links
    via = defaultdict(set)
    for src in (a, b):
        for r in src['tables'].get('report_cohort_links', []):
            for k in ('cohort_id', 'study_id'):
                if r.get(k) and r.get('report_id'):
                    via[(k, r[k])].add(r['report_id'])

    def report_of(t, row_a, row_b, key_value):
        for r in (row_a, row_b):
            if r.get('report_id'):
                return r['report_id']
        if t == 'extraction_provenance' or key_value.startswith('PILOT-'):
            return key_value
        k = 'cohort_id' if t == 'cohorts' else ('study_id' if t == 'study_families' else None)
        ids = set()
        for r in (row_a, row_b):
            if k and r.get(k):
                ids |= via[(k, r[k])]
        return '; '.join(sorted(ids))
    skip = set(NOT_SCORED)
    if a['is_pilot'] and b['is_pilot']:      # generator-filled bibliographic cells are identical by construction
        skip |= {('reports', c) for c in bw.PILOT_REPORT_PREFILL}
    for t, S in schema['tables'].items():
        rows_a, rows_b = a['tables'].get(t, []), b['tables'].get(t, [])
        key = ALIGN_BY_REPORT.get(t, S['pk'])
        pairs, only_a, only_b, method, dups = align(rows_a, rows_b, key, mode)
        rids = sorted({r.get('report_id', '') for r in rows_a + rows_b} - {''}) if 'report_id' in S['fields'] else []
        for rid in rids:
            coverage.append({'table': t, 'report_id': rid,
                             f'rows_{la}': sum(1 for r in rows_a if r.get('report_id') == rid),
                             f'rows_{lb}': sum(1 for r in rows_b if r.get('report_id') == rid)})
        for side, lst in ((la, only_a), (lb, only_b)):
            for k, r in lst:
                disagreements.append({'table': t, 'align_key': k, 'report_id': r.get('report_id', ''), 'field': '(row)',
                                      'family': '', 'value_kind': '', 'category': f'row_only_{side}',
                                      f'value_{la}': json.dumps(r, ensure_ascii=False) if side == la else '',
                                      f'value_{lb}': json.dumps(r, ensure_ascii=False) if side == lb else ''})
        # columns to compare
        fields = []
        paired_b = set(S['slots'].values()) if pair_slots else set()
        for f in S['fields']:
            if f in paired_b or (t, f) in skip:
                continue
            if pair_slots and f in S['slots']:
                fields.append((slot_col(f, '<own slot>'), slot_col(f, slot_a), slot_col(f, slot_b), S['cols'][f]))
            else:
                fields.append((f, f, f, S['cols'][f]))
        if pair_slots:
            for f in S['slots']:
                for side, rows, own in ((la, rows_a, slot_a), (lb, rows_b, slot_b)):
                    for other in ('A', 'B'):
                        if other == own:
                            continue
                        col = slot_col(f, other)
                        for r in rows:
                            if r.get(col):
                                slot_warn.append({'table': t, 'reviewer': side, 'column': col,
                                                  'report_id': r.get('report_id', ''), 'value': r[col]})
        tc = Counter()
        for k, ra, rb in pairs:
            rid = report_of(t, ra, rb, k)
            for name, fa, fb, meta in fields:
                if method.startswith('key:') and fa == key:
                    continue
                va, vb = norm_value(ra.get(fa, ''), meta), norm_value(rb.get(fb, ''), meta)
                fid = (t, name)
                meta_of[fid] = meta
                if not va and not vb:
                    by_field[fid]['both_empty'] += 1
                    empty.append((t, name, rid, meta))
                    continue
                cat = 'agree' if va == vb else ('disagree' if va and vb else (f'only_{la}' if va else f'only_{lb}'))
                by_field[fid][cat] += 1
                tc[cat] += 1
                tc[f'{meta["kind"]}:{cat}'] += 1
                if cat != 'agree':
                    disagreements.append({'table': t, 'align_key': k, 'report_id': rid, 'field': name,
                                          'family': meta['family'], 'value_kind': meta['kind'], 'category': cat,
                                          f'value_{la}': ra.get(fa, ''), f'value_{lb}': rb.get(fb, '')})
        tables_out[t] = {'align': method, 'rows': {la: len(rows_a), lb: len(rows_b)}, 'rows_matched': len(pairs),
                         f'rows_only_{la}': len(only_a), f'rows_only_{lb}': len(only_b), 'duplicate_keys': dups,
                         **metrics(tc, la, lb), 'coded_and_counts_only': metrics(non_free_text(tc), la, lb)}
    # empty-by-both: per table/field/report (group rows of the same report)
    grouped = defaultdict(int)
    for t, name, rid, meta in empty:
        grouped[(t, name, rid)] += 1
    empty_rows = []
    for (t, name, rid), n in grouped.items():
        base = name.replace('<own slot>', 'A')
        flags = set()
        for fld in {base, name, name.replace('<own slot>', 'B')}:
            for r in [x.strip() for x in rid.split(';')] + ['']:
                flags |= flagged.get((t, fld, r), set())
        if 'not_extractable_from_text' in flags:
            cand = 'not_extractable_from_text (flagged in pilot_notes)'
        elif flags:
            cand = 'manual_or_dictionary_unclear (flagged in pilot_notes: ' + ', '.join(sorted(flags)) + ')'
        else:
            cand = 'unflagged: D to classify (not extractable from text / manual unclear / not attempted)'
        empty_rows.append({'table': t, 'field': name, 'family': schema['tables'][t]['cols'].get(base, {}).get('family', ''),
                           'report_id': rid, 'matched_rows_both_empty': n, 'candidate_reason': cand})
    # field / family summaries
    field_rows, fam = [], defaultdict(Counter)
    for (t, name), c in by_field.items():
        meta = meta_of[(t, name)]
        field_rows.append({'table': t, 'field': name, 'family': meta['family'], 'value_kind': meta['kind'],
                           **metrics(c, la, lb), 'both_empty': c['both_empty']})
        for k in ('agree', 'disagree', f'only_{la}', f'only_{lb}'):
            fam[meta['family']][k] += c[k]
            if meta['kind'] in ('coded', 'count'):
                fam[meta['family']]['nf:' + k] += c[k]
    fam_rows = [{'family': f, **metrics(c, la, lb), 'coded_and_counts_only': metrics(
        Counter({k[3:]: v for k, v in c.items() if k.startswith('nf:')}), la, lb)} for f, c in sorted(fam.items())]
    total = Counter()
    for r in tables_out.values():
        for k in ('agree', 'disagree', f'only_{la}', f'only_{lb}'):
            total[k] += r[k]
    mins = []
    for rid in sorted(set(a['minutes']) | set(b['minutes'])):
        ma, mb = a['minutes'].get(rid, {}), b['minutes'].get(rid, {})
        mins.append({'report_id': rid, f'minutes_{la}': ma.get('minutes', ''), f'minutes_{lb}': mb.get('minutes', ''),
                     f'unresolved_questions_{la}': ma.get('questions', ''),
                     f'unresolved_questions_{lb}': mb.get('questions', '')})
    return {'tables': tables_out, 'fields': field_rows, 'families': fam_rows, 'overall': metrics(total, la, lb),
            'disagreements': disagreements, 'empty_by_both': empty_rows, 'coverage': coverage,
            'slot_warnings': slot_warn, 'minutes': mins, 'notes': notes,
            'not_scored': sorted(f'{t}.{f}' for t, f in skip),
            'date_finished': {la: a['date_finished'], lb: b['date_finished']}}


def non_free_text(c: Counter) -> Counter:
    """Coded and count cells only (identifiers and free text removed)."""
    out = Counter()
    for k, n in c.items():
        if ':' in k and k.split(':', 1)[0] in ('coded', 'count'):
            out[k.split(':', 1)[1]] += n
    return out


def slot_col(f: str, slot: str) -> str:
    toks = re.split(r'([_.])', f)
    i = max(i for i, tok in enumerate(toks) if tok == 'A')
    return ''.join(toks[:i] + [slot] + toks[i + 1:])


def metrics(c: Counter, la: str, lb: str) -> dict:
    agree, dis, oa, ob = c['agree'], c['disagree'], c[f'only_{la}'], c[f'only_{lb}']
    both, anyf = agree + dis, agree + dis + oa + ob
    return {'cells_compared': anyf, 'agree': agree, 'disagree': dis, f'only_{la}': oa, f'only_{lb}': ob,
            'agreement_both_filled': round(agree / both, 4) if both else None,
            'agreement_any_filled': round(agree / anyf, 4) if anyf else None}


def flat(d: dict) -> dict:
    out = {}
    for k, v in d.items():
        if isinstance(v, dict):
            for k2, v2 in v.items():
                out[f'{k}.{k2}'] = v2
        elif isinstance(v, list):
            out[k] = '; '.join(map(str, v))
        else:
            out[k] = v
    return out


def write_outputs(res: dict, out_dir: Path, info: dict, la: str, lb: str) -> dict:
    out_dir.mkdir(parents=True, exist_ok=True)

    def dump(name, rows, cols=None):
        rows = [flat(r) for r in rows]
        cols = cols or list(dict.fromkeys(k for r in rows for k in r)) or ['(none)']
        write_csv(out_dir / name, cols, rows)

    dump('agreement_by_table.csv', [{'table': t, **v} for t, v in res['tables'].items()])
    dump('agreement_by_family.csv', res['families'])
    dump('agreement_by_field.csv', sorted(res['fields'], key=lambda r: (r['table'], r['field'])))
    dump('disagreements.csv', res['disagreements'],
         ['table', 'report_id', 'align_key', 'field', 'family', 'value_kind', 'category', f'value_{la}', f'value_{lb}'])
    dump('empty_by_both.csv', sorted(res['empty_by_both'], key=lambda r: (r['table'], r['field'], r['report_id'])),
         ['table', 'field', 'family', 'report_id', 'matched_rows_both_empty', 'candidate_reason'])
    dump('row_coverage.csv', res['coverage'], ['table', 'report_id', f'rows_{la}', f'rows_{lb}'])
    dump('minutes_and_questions.csv', res['minutes'],
         ['report_id', f'minutes_{la}', f'minutes_{lb}', f'unresolved_questions_{la}', f'unresolved_questions_{lb}'])
    dump('pilot_notes_combined.csv', res['notes'], ['reviewer'] + bw.PILOT_NOTES_COLUMNS)
    cat = Counter(d['category'] for d in res['disagreements'])
    summary = {
        'generated_at_utc': _dt.datetime.now(_dt.timezone.utc).isoformat(timespec='seconds'),
        'generator': 'scripts/compare_extraction.py', **info,
        'status': 'Descriptive agreement between two independent extractions; not results. Free-text exact-match '
                  'agreement is reported but should be read, not scored.',
        'overall': res['overall'], 'disagreement_categories': dict(cat),
        'not_scored_columns': res['not_scored'],
        'tables': res['tables'], 'families': res['families'],
        'empty_by_both': {'cells': sum(r['matched_rows_both_empty'] for r in res['empty_by_both']),
                          'table_field_report_entries': len(res['empty_by_both'])},
        'slot_warnings': res['slot_warnings'], 'date_finished': res['date_finished'],
        'pilot_notes': {la: sum(1 for n in res['notes'] if n['reviewer'] == la),
                        lb: sum(1 for n in res['notes'] if n['reviewer'] == lb)},
        'outputs': sorted(p.name for p in out_dir.glob('*.csv')),
    }
    (out_dir / 'agreement_summary.json').write_text(json.dumps(summary, ensure_ascii=False, indent=2) + '\n')
    return summary


def run_compare(args) -> int:
    schema = load_schema()
    a, b = read_source(args.a, schema), read_source(args.b, schema)
    res = compare(a, b, schema, args.label_a, args.label_b, args.slot_a, args.slot_b, args.align,
                  pair_slots=not args.no_slot_pairing)
    info = {'inputs': {args.label_a: {'path': str(args.a), 'sha256': a['sha256']},
                       args.label_b: {'path': str(args.b), 'sha256': b['sha256']}},
            'slots': {args.label_a: args.slot_a, args.label_b: args.slot_b},
            'dictionary_sha256': schema['dictionary_sha256'], 'align_mode': args.align}
    s = write_outputs(res, args.out_dir, info, args.label_a, args.label_b)
    print(json.dumps({'out_dir': str(args.out_dir), 'overall': s['overall'],
                      'disagreement_categories': s['disagreement_categories'],
                      'empty_by_both': s['empty_by_both'], 'slot_warnings': len(s['slot_warnings'])}, ensure_ascii=False))
    return 0


