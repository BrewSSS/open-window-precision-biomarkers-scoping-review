def load_schema() -> dict:
    src = bw.load_sources()
    tables, *_ = bw.extraction_fields(src)
    schema = {}
    for t, info in tables.items():
        pk = info['spec']['primary_key']
        cols = {}
        names = [m['field'] for m in info['fields']]
        for m in info['fields']:
            f = m['field']
            if m['is_id']:
                kind = 'identifier'
            elif m['is_count']:
                kind = 'count'
            elif m['list_name']:
                kind = 'coded'
            else:
                kind = 'free_text'
            cols[f] = {'kind': kind, 'is_list': m['is_list'], 'family': family_of(f, m), 'is_id': m['is_id']}
        schema[t] = {'pk': pk, 'fields': names, 'cols': cols, 'slots': slot_pairs(names)}
    return {'tables': schema, 'dictionary_sha256': src['dictionary']['sha256']}


def family_of(field: str, meta: dict) -> str:
    if meta['is_id']:
        return 'keys'
    if meta['legacy']:
        return meta['legacy']['module']
    if 'locator' in field and field not in NONLEGACY_FAMILY:
        return 'source_locator'
    if field.endswith('notes'):
        return 'notes'
    base = re.sub(r'_[AB]$', '', field)
    for k, fam in NONLEGACY_FAMILY.items():
        if field == k or base == k or (k.endswith('_') and field.startswith(k)) or (k == 'digitiz' and 'digitiz' in field):
            return fam
    return 'other'


def slot_pairs(names) -> dict:
    """{slot-A column: slot-B column} for columns that differ only by an upper-case A/B token."""
    pairs = {}
    for f in names:
        toks = re.split(r'([_.])', f)
        for i, tok in enumerate(toks):
            if tok == 'A':
                other = ''.join(toks[:i] + ['B'] + toks[i + 1:])
                if other in names:
                    pairs[f] = other
    return pairs


